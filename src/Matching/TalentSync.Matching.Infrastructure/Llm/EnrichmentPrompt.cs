using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using Microsoft.Extensions.AI;
using TalentSync.Matching.Domain;

namespace TalentSync.Matching.Infrastructure.Llm;

/// <summary>
/// What the model is asked, the answer schema, and a version derived from both. The version is part of the key of
/// stored suggestions, so any change to the instructions or the schema asks the model again instead of replaying
/// answers to the old prompt.
/// </summary>
internal static class EnrichmentPrompt
{
    private const int VersionLength = 16;

    // The limit comes from the domain, so the prompt cannot drift from the validation that rejects the answer.
    public static readonly string Instructions = $"""
        You read the CV of an IT consultant and suggest their technical skills and seniority.
        Each skill is a short name of at most {Skill.MaxLength} characters.
        Seniority is one of: Junior, Mid, Senior, Lead.
        Confidence is how sure you are of the whole assessment, from 0 to 1.
        Use only what the CV says. Answer with JSON only.
        """;

    public static readonly JsonSerializerOptions JsonOptions = new(JsonSerializerDefaults.Web);

    public static readonly ChatResponseFormatJson ResponseFormat = ChatResponseFormat.ForJsonSchema<EnrichmentResponseDto>(
        JsonOptions, "consultant_enrichment", "Suggested skills and seniority of a consultant.");

    // The schema is generated by Microsoft.Extensions.AI, so a package upgrade that changes it also gives a new
    // version: the model then sees a different request, so its stored answers are not reused.
    public static readonly string Version = VersionOf(Instructions, ResponseFormat);

    internal static string VersionOf(string instructions, ChatResponseFormatJson responseFormat)
    {
        var text = string.Join('\n', instructions, responseFormat.SchemaName, responseFormat.SchemaDescription,
            responseFormat.Schema?.GetRawText());
        return Convert.ToHexStringLower(SHA256.HashData(Encoding.UTF8.GetBytes(text)))[..VersionLength];
    }
}
